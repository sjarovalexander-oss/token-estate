export const retLabel = (p) =>
  p.type === 'exit'
    ? Math.round((p.payout / p.price - 1) * 100) + '% за ' + p.months + ' мес.'
    : Math.round(p.yld * 100) + '% годишно';

export function fairValue(p, st) {
  const base = p.stages[st.stage].fair;
  if (p.type === 'exit' && st.stage === last(p)) return Math.round(base + (p.payout - base) * 0.5 * (st.prog / p.N));
  return base;
}
export function paidPer(p, st) {
  if (st.stage < last(p)) return 0;
  if (p.type === 'exit') return (p.payout * st.prog) / p.N;
  return (p.price * p.yld * st.prog) / 4 + (st.prog === p.N ? p.price : 0);
}
export function platformRevenue(p, st) {
  const raise = st.stage > 0 ? target(p) * FEE.raise : 0;
  const frac = st.stage === last(p) ? st.prog / p.N : 0;
  const success = p.type === 'exit' ? p.profit * FEE.profit * frac : (target(p) * FEE.manage * (st.stage === last(p) ? st.prog : 0)) / 4;
  return { raise, success, trade: st.fees, total: raise + success + st.fees };
}

