// Нов проект от одобрена заявка: взима етапите и кадрите от образеца на секцията
export function makeProject(a) {
  const base = PROJECTS.find((p) => p.cat === a.cat);
  const price = +a.price, tokens = Math.max(10, Math.round(a.amount / price)), ret = a.ret / 100;
  const exit = base.type === 'exit';
  const k = exit ? a.term / base.months : 1;
  const p = {
    ...base, id: 'c' + a.id, custom: true, name: a.name, loc: a.loc, tagline: a.tagline || 'Нов проект, одобрен от екипа на платформата.',
    tokens, price, sold0: 0, bonus: undefined,
    spv: 'Отделно дружество за проекта', partner: 'Собственик: ' + a.company,
    stages: base.stages.map((s) => ({ ...s, month: exit ? Math.round(s.month * k) : s.month, fair: Math.round((s.fair / base.price) * price) })),
    facts: [['Търсено финансиране', eur(tokens * price)], ['Токени (' + tokens + ' × ' + eur(price) + ')', eur(tokens * price)], ['Предложена доходност', a.ret + '%' + (exit ? ' за ' + a.term + ' мес.' : ' годишно')]],
  };
  if (exit) Object.assign(p, { months: +a.term, payout: Math.round(price * (1 + ret)), profit: Math.round(tokens * price * ret * 2.5) });
  else Object.assign(p, { yld: ret, years: +a.term, N: a.term * 4 });
  return p;
}

